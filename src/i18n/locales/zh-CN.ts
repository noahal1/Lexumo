type DeepStrings<T> = {
  [K in keyof T]: T[K] extends string ? string : DeepStrings<T[K]>;
};

export type Dictionary = DeepStrings<typeof zhCNraw>;

export const zhCN: Dictionary = zhCNraw;

type Paths<T> = {
  [K in keyof T & string]: T[K] extends string ? K : `${K}.${Paths<T[K]>}`;
}[keyof T & string];

/**
 * Every key the dictionary actually has, as a dot-path union.
 *
 * `t()` used to accept any string, so a misspelled key compiled fine and the
 * user saw the key itself rendered as body text. Deriving the union from the
 * dictionary moves that failure to compile time — and deleting a key now flags
 * every call site that still asks for it.
 */
export type MessageKey = Paths<typeof zhCNraw>;
